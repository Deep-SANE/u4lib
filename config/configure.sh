#!/usr/bin/env bash
# u4lib configuration — inherits toolchain and core dependencies from u3lib,
# and writes config/config.generated.mk. Run via `make config` (or directly).
#
# Usage:
#   ./configure.sh [--u3lib=PATH] [--yes|-y]
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GEN="$ROOT/config/config.generated.mk"

say()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mnote:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

YES=0
OPT_u3lib=""
OPT_solver=""

for arg in "$@"; do
  case "$arg" in
    --yes|-y) YES=1 ;;
    --u3lib=*) OPT_u3lib="${arg#*=}" ;;
    --solver=*) OPT_solver="${arg#*=}" ;;
    --help|-h)
      echo "Usage: ./configure.sh [--u3lib=PATH] [--solver=qr|sns] [--yes]"
      exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

say "Configuring u4lib (DeepSANE)"

# 1. Prerequisite Gate: Resolve and validate u3lib
U3LIB_DIR="${OPT_u3lib:-${U3LIB_DIR:-}}"

if [[ -z "$U3LIB_DIR" ]]; then
  DEFAULT_U3LIB=""
  if [[ -f "$ROOT/../u3lib/include/u3lib.h" ]]; then
    DEFAULT_U3LIB="$(cd "$ROOT/../u3lib" 2>/dev/null && pwd || true)"
  fi

  if [[ -z "$DEFAULT_U3LIB" ]]; then
    die "u3lib was not found!
u4lib requires u3lib as a prerequisite for group-theoretic utilities and numerical backends.
Please clone and configure u3lib first:
  git clone git@github.com:Deep-SANE/u3lib.git ../u3lib
  cd ../u3lib && make config && make"
  fi

  if [[ $YES -eq 1 ]]; then
    U3LIB_DIR="${DEFAULT_U3LIB}"
  else
    read -r -p "Path to u3lib [$DEFAULT_U3LIB]: " ans </dev/tty || ans=""
    U3LIB_DIR="${ans:-$DEFAULT_U3LIB}"
  fi
fi

U3LIB_DIR="$(cd "$U3LIB_DIR" 2>/dev/null && pwd || echo "$U3LIB_DIR")"
if [[ ! -d "$U3LIB_DIR" || ! -f "$U3LIB_DIR/include/u3lib.h" ]]; then
  die "u3lib not found at: $U3LIB_DIR (missing include/u3lib.h)
Please ensure u3lib is available and points to a valid u3lib repository."
fi

U3_CONFIG="$U3LIB_DIR/config/config.generated.mk"
if [[ ! -f "$U3_CONFIG" ]]; then
  die "u3lib at '$U3LIB_DIR' is not configured yet (missing $U3_CONFIG).
u4lib inherits its toolchain and dependencies from u3lib.
Please configure and build u3lib first:
  cd \"$U3LIB_DIR\" && make config && make"
fi

# Helper to extract settings from u3lib's config.generated.mk
get_var() {
  grep -E "^[[:space:]]*$1[[:space:]]*:=" "$U3_CONFIG" | head -n1 | sed -E "s/^[[:space:]]*$1[[:space:]]*:=[[:space:]]*//" || true
}

# Verify u3lib's Wigner backend is compiled if using local external-libs
USE_WIGNERNJ="$(get_var USE_WIGNERNJ)"
WIGNERNJ_DIR="$(get_var WIGNERNJ_DIR)"
if [[ "$USE_WIGNERNJ" == "1" && -n "$WIGNERNJ_DIR" ]]; then
  if [[ ! -d "$WIGNERNJ_DIR" ]] || \
     ( [[ ! -f "$WIGNERNJ_DIR/lib/libwignernj.dylib" ]] && \
       [[ ! -f "$WIGNERNJ_DIR/lib/libwignernj.so" ]] && \
       [[ ! -f "$WIGNERNJ_DIR/lib/libwignernj.a" ]] && \
       [[ ! -f "$WIGNERNJ_DIR/lib64/libwignernj.so" ]] && \
       [[ ! -f "$WIGNERNJ_DIR/lib64/libwignernj.a" ]] ); then
    die "u3lib's Wigner backend ($WIGNERNJ_DIR) has not been built yet.
Please build u3lib first:
  cd \"$U3LIB_DIR\" && make"
  fi
fi

say "Found u3lib at: $U3LIB_DIR"
say "Inheriting toolchain and dependency settings from u3lib..."

CXX="$(get_var CXX)"
CXXFLAGS="$(get_var CXXFLAGS)"
LDFLAGS="$(get_var LDFLAGS)"
USE_WIGNERNJ="$(get_var USE_WIGNERNJ)"
WIGNERNJ_DIR="$(get_var WIGNERNJ_DIR)"
USE_SNS="$(get_var USE_SNS)"
SNS_DIR="$(get_var SNS_DIR)"
NULLSPACE_SOLVER="${OPT_solver:-qr}"
BOOST_ROOT="$(get_var BOOST_ROOT)"
EIGEN_DIR="$(get_var EIGEN_DIR)"
HAVE_FMT="$(get_var HAVE_FMT)"
FMT_HEADER_ONLY="$(get_var FMT_HEADER_ONLY)"
FMT_DIR="$(get_var FMT_DIR)"
USE_OPENMP="$(get_var USE_OPENMP)"
OMP_CXXFLAGS="$(get_var OMP_CXXFLAGS)"
OMP_LDFLAGS="$(get_var OMP_LDFLAGS)"

# Write config.generated.mk
cat > "$GEN" <<EOF
# Generated by config/configure.sh on $(date). Re-run \`make config\` to change.
U3LIB_DIR := $U3LIB_DIR
CXX := $CXX
CXXFLAGS := $CXXFLAGS
LDFLAGS := $LDFLAGS
USE_WIGNERNJ := $USE_WIGNERNJ
WIGNERNJ_DIR := $WIGNERNJ_DIR
USE_SNS := $USE_SNS
SNS_DIR := $SNS_DIR
NULLSPACE_SOLVER := $NULLSPACE_SOLVER
BOOST_ROOT := $BOOST_ROOT
EIGEN_DIR := $EIGEN_DIR
HAVE_FMT := $HAVE_FMT
FMT_HEADER_ONLY := $FMT_HEADER_ONLY
FMT_DIR := $FMT_DIR
USE_OPENMP := $USE_OPENMP
OMP_CXXFLAGS := $OMP_CXXFLAGS
OMP_LDFLAGS := $OMP_LDFLAGS
EOF

say "Configuration written to $GEN"
say "Ready to build: run 'make' (driver programs), 'make test' (regression suite), or 'make python'"
