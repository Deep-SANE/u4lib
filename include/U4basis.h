  /*------------------------------------------------------
  A structure for Gelfand basis state
  |n14, n24, n34, n44\
  |   n13, n23, n33   \
  |      n12, n22     /
  |         n11      /
  */
  struct gelfand
  {
    int n14, n24, n34, n44, n13, n23, n33, n12, n22, n11;

    // Default constructor
    gelfand()
        : n14(0),
          n24(0),
          n34(0),
          n44(0),
          n13(0),
          n23(0),
          n33(0),
          n12(0),
          n22(0),
          n11(0)
    { }

    // initialization
    gelfand(int a, int b, int c, int d, int e, int f, int g, int h, int i,
            int j)
    {
      n14 = a;
      n24 = b;
      n34 = c;
      n44 = d;
      n13 = e;
      n23 = f;
      n33 = g;
      n12 = h;
      n22 = i;
      n11 = j;
    }

    // assigment operator
    gelfand& operator=(const gelfand& g)
    {
      n14 = g.n14;
      n24 = g.n24;
      n34 = g.n34;
      n44 = g.n44;
      n13 = g.n13;
      n23 = g.n23;
      n33 = g.n33;
      n12 = g.n12;
      n22 = g.n22;
      n11 = g.n11;
      return *this;
    }

    // check betweenness condition
    bool check()
    {
      if (n14 >= n13 && n13 >= n24 && n24 >= n23 && n23 >= n34 && n34 >= n33 &&
          n33 >= n44 && n13 >= n12 && n12 >= n23 && n23 >= n22 && n22 >= n33 &&
          n12 >= n11 && n11 >= n22)
      {
        return true;
      }
      else
      {
        return false;
      }
    }

    // normalize the pattern
    void normalize()
    {
      n14 -= n44;
      n24 -= n44;
      n34 -= n44;
      n13 -= n44;
      n23 -= n44;
      n33 -= n44;
      n12 -= n44;
      n22 -= n44;
      n11 -= n44;
      n44 = 0;
    }

    // coefficients generated by acting upon with generators

    // generators that do not change the state
    double e11() { return n11; }
    double e22() { return n12 + n22 - n11; }
    double e33() { return n13 + n23 + n33 - n12 - n22; }
    double e44() { return n14 + n24 + n34 + n44 - n13 - n23 - n33; }

    // generators that change the state
    double e12() { return std::sqrt((n12 - n11) * (n11 - n22 + 1.0)); }
    //
    double e21() { return std::sqrt((n12 - n11 + 1.0) * (n11 - n22)); }
    //
    double e23_12()
    {
      return std::sqrt((n13 - n12) * (n12 - n23 + 1.0) * (n12 - n33 + 2.0) *
                       (n12 - n11 + 1.0) / (n12 - n22 + 2.0) /
                       (n12 - n22 + 1.0));
    }
    double e23_22()
    {
      return std::sqrt((n13 - n22 + 1.0) * (n23 - n22) * (n22 - n33 + 1.0) *
                       (n11 - n22) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    //
    double e32_12()
    {
      return std::sqrt((n13 - n12 + 1.0) * (n12 - n23) * (n12 - n33 + 1.0) *
                       (n12 - n11) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e32_22()
    {
      return std::sqrt((n13 - n22 + 2.0) * (n23 - n22 + 1.0) * (n22 - n33) *
                       (n11 - n22 + 1.0) / (n12 - n22 + 2.0) /
                       (n12 - n22 + 1.0));
    }
    //
    double e13_12()
    {
      return std::sqrt((n13 - n12) * (n12 - n23 + 1.0) * (n12 - n33 + 2.0) *
                       (n11 - n22 + 1.0) / (n12 - n22 + 2.0) /
                       (n12 - n22 + 1.0));
    }
    double e13_22()
    {
      return -std::sqrt((n13 - n22 + 1.0) * (n23 - n22) * (n22 - n33 + 1.0) *
                        (n12 - n11) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    //
    double e31_12()
    {
      return std::sqrt((n13 - n12 + 1.0) * (n12 - n23) * (n12 - n33 + 1.0) *
                       (n11 - n22) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e31_22()
    {
      return -std::sqrt((n13 - n22 + 2.0) * (n23 - n22 + 1.0) * (n22 - n33) *
                        (n12 - n11 + 1.0) / (n12 - n22 + 2.0) /
                        (n12 - n22 + 1.0));
    }
    //
    double e34_13()
    {
      return std::sqrt((n14 - n13) * (n13 - n24 + 1.0) * (n13 - n34 + 2.0) *
                       (n13 - n44 + 3.0) * (n13 - n12 + 1.0) *
                       (n13 - n22 + 2.0) / (n13 - n23 + 2.0) /
                       (n13 - n23 + 1.0) / (n13 - n33 + 3.0) /
                       (n13 - n33 + 2.0));
    }
    double e34_23()
    {
      return std::sqrt((n14 - n23 + 1.0) * (n24 - n23) * (n23 - n34 + 1.0) *
                       (n23 - n44 + 2.0) * (n12 - n23) * (n23 - n22 + 1.0) /
                       (n13 - n23 + 1.0) / (n13 - n23) / (n23 - n33 + 2.0) /
                       (n23 - n33 + 1.0));
    }
    double e34_33()
    {
      return std::sqrt((n14 - n33 + 2.0) * (n24 - n33 + 1.0) * (n34 - n33) *
                       (n33 - n44 + 1.0) * (n12 - n33 + 1.0) * (n22 - n33) /
                       (n13 - n33 + 2.0) / (n13 - n33 + 1.0) /
                       (n23 - n33 + 1.0) / (n23 - n33));
    }
    //
    double e43_13()
    {
      return std::sqrt((n14 - n13 + 1) * (n13 - n24) * (n13 - n34 + 1.0) *
                       (n13 - n44 + 2.0) * (n13 - n12) * (n13 - n22 + 1.0) /
                       (n13 - n23 + 1.0) / (n13 - n23) / (n13 - n33 + 2.0) /
                       (n13 - n33 + 1.0));
    }
    double e43_23()
    {
      return std::sqrt((n14 - n23 + 2.0) * (n24 - n23 + 1.0) * (n23 - n34) *
                       (n23 - n44 + 1.0) * (n12 - n23 + 1.0) * (n23 - n22) /
                       (n13 - n23 + 2.0) / (n13 - n23 + 1.0) /
                       (n23 - n33 + 1.0) / (n23 - n33));
    }
    double e43_33()
    {
      return std::sqrt((n14 - n33 + 3.0) * (n24 - n33 + 2.0) *
                       (n34 - n33 + 1.0) * (n33 - n44) * (n12 - n33 + 2.0) *
                       (n22 - n33 + 1.0) / (n13 - n33 + 3.0) /
                       (n13 - n33 + 2.0) / (n23 - n33 + 2.0) /
                       (n23 - n33 + 1.0));
    }
    //
    double e24_13_12()
    {
      return std::sqrt(
          (n14 - n13) * (n13 - n24 + 1.0) * (n13 - n34 + 2.0) *
          (n13 - n44 + 3.0) * (n12 - n23 + 1.0) * (n12 - n33 + 2.0) *
          (n13 - n22 + 2.0) * (n12 - n11 + 1.0) / (n13 - n23 + 2.0) /
          (n13 - n23 + 1.0) / (n13 - n33 + 3.0) / (n13 - n33 + 2.0) /
          (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
    double e24_13_22()
    {
      return std::sqrt((n14 - n13) * (n13 - n24 + 1.0) * (n13 - n34 + 2.0) *
                       (n13 - n44 + 3.0) * (n23 - n22) * (n22 - n33 + 1.0) *
                       (n13 - n12 + 1.0) * (n11 - n22) / (n13 - n23 + 2.0) /
                       (n13 - n23 + 1.0) / (n13 - n33 + 3.0) /
                       (n13 - n33 + 2.0) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e24_23_12()
    {
      return -std::sqrt((n14 - n23 + 1.0) * (n24 - n23) * (n23 - n34 + 1.0) *
                        (n23 - n44 + 2.0) * (n13 - n12) * (n12 - n33 + 2.0) *
                        (n23 - n22 + 1.0) * (n12 - n11 + 1.0) /
                        (n13 - n23 + 1.0) / (n13 - n23) / (n23 - n33 + 2.0) /
                        (n23 - n33 + 1.0) / (n12 - n22 + 2.0) /
                        (n12 - n22 + 1.0));
    }
    double e24_23_22()
    {
      return std::sqrt((n14 - n23 + 1.0) * (n24 - n23) * (n23 - n34 + 1.0) *
                       (n23 - n44 + 2.0) * (n13 - n22 + 1.0) *
                       (n22 - n33 + 1.0) * (n12 - n23) * (n11 - n22) /
                       (n13 - n23 + 1.0) / (n13 - n23) / (n23 - n33 + 2.0) /
                       (n23 - n33 + 1.0) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e24_33_12()
    {
      return -std::sqrt((n14 - n33 + 2.0) * (n24 - n33 + 1.0) * (n34 - n33) *
                        (n33 - n44 + 1.0) * (n13 - n12) * (n12 - n23 + 1.0) *
                        (n22 - n33) * (n12 - n11 + 1.0) / (n13 - n33 + 2.0) /
                        (n13 - n33 + 1.0) / (n23 - n33 + 1.0) / (n23 - n33) /
                        (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
    double e24_33_22()
    {
      return -std::sqrt((n14 - n33 + 2.0) * (n24 - n33 + 1.0) * (n34 - n33) *
                        (n33 - n44 + 1.0) * (n13 - n22 + 1.0) * (n23 - n22) *
                        (n12 - n33 + 1.0) * (n11 - n22) / (n13 - n33 + 2.0) /
                        (n13 - n33 + 1.0) / (n23 - n33 + 1.0) / (n23 - n33) /
                        (n12 - n22 + 1.0) / (n12 - n22));
    }
    //
    double e42_13_12()
    {
      return std::sqrt((n14 - n13 + 1.0) * (n13 - n24) * (n13 - n34 + 1.0) *
                       (n13 - n44 + 2.0) * (n12 - n23) * (n12 - n33 + 1.0) *
                       (n13 - n22 + 1.0) * (n12 - n11) / (n13 - n23 + 1.0) /
                       (n13 - n23) / (n13 - n33 + 2.0) / (n13 - n33 + 1.0) /
                       (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e42_13_22()
    {
      return std::sqrt((n14 - n13 + 1.0) * (n13 - n24) * (n13 - n34 + 1.0) *
                       (n13 - n44 + 2.0) * (n23 - n22 + 1.0) * (n22 - n33) *
                       (n13 - n12) * (n11 - n22 + 1.0) / (n13 - n23 + 1.0) /
                       (n13 - n23) / (n13 - n33 + 2.0) / (n13 - n33 + 1.0) /
                       (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
    double e42_23_12()
    {
      return -std::sqrt(
          (n14 - n23 + 2.0) * (n24 - n23 + 1.0) * (n23 - n34) *
          (n23 - n44 + 1.0) * (n13 - n12 + 1.0) * (n12 - n33 + 1.0) *
          (n23 - n22) * (n12 - n11) / (n13 - n23 + 2.0) / (n13 - n23 + 1.0) /
          (n23 - n33 + 1.0) / (n23 - n33) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e42_23_22()
    {
      return std::sqrt((n14 - n23 + 2.0) * (n24 - n23 + 1.0) * (n23 - n34) *
                       (n23 - n44 + 1.0) * (n13 - n22 + 2.0) * (n22 - n33) *
                       (n12 - n23 + 1.0) * (n11 - n22 + 1.0) /
                       (n13 - n23 + 2.0) / (n13 - n23 + 1.0) /
                       (n23 - n33 + 1.0) / (n23 - n33) / (n12 - n22 + 2.0) /
                       (n12 - n22 + 1.0));
    }
    double e42_33_12()
    {
      return -std::sqrt((n14 - n33 + 3.0) * (n24 - n33 + 2.0) *
                        (n34 - n33 + 1.0) * (n33 - n44) * (n13 - n12 + 1.0) *
                        (n12 - n23) * (n22 - n33 + 1.0) * (n12 - n11) /
                        (n13 - n33 + 3.0) / (n13 - n33 + 2.0) /
                        (n23 - n33 + 2.0) / (n23 - n33 + 1.0) /
                        (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e42_33_22()
    {
      return -std::sqrt(
          (n14 - n33 + 3.0) * (n24 - n33 + 2.0) * (n34 - n33 + 1.0) *
          (n33 - n44) * (n13 - n22 + 2.0) * (n23 - n22 + 1.0) *
          (n12 - n33 + 2.0) * (n11 - n22 + 1.0) / (n13 - n33 + 3.0) /
          (n13 - n33 + 2.0) / (n23 - n33 + 2.0) / (n23 - n33 + 1.0) /
          (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
    //
    double e14_13_12()
    {
      return std::sqrt(
          (n14 - n13) * (n13 - n24 + 1.0) * (n13 - n34 + 2.0) *
          (n13 - n44 + 3.0) * (n12 - n23 + 1.0) * (n12 - n33 + 2.0) *
          (n13 - n22 + 2.0) * (n11 - n22 + 1.0) / (n13 - n23 + 2.0) /
          (n13 - n23 + 1.0) / (n13 - n33 + 3.0) / (n13 - n33 + 2.0) /
          (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
    double e14_13_22()
    {
      return -std::sqrt((n14 - n13) * (n13 - n24 + 1.0) * (n13 - n34 + 2.0) *
                        (n13 - n44 + 3.0) * (n23 - n22) * (n22 - n33 + 1.0) *
                        (n13 - n12 + 1.0) * (n12 - n11) / (n13 - n23 + 2.0) /
                        (n13 - n23 + 1.0) / (n13 - n33 + 3.0) /
                        (n13 - n33 + 2.0) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e14_23_12()
    {
      return -std::sqrt((n14 - n23 + 1.0) * (n24 - n23) * (n23 - n34 + 1.0) *
                        (n23 - n44 + 2.0) * (n13 - n12) * (n12 - n33 + 2.0) *
                        (n23 - n22 + 1.0) * (n11 - n22 + 1.0) /
                        (n13 - n23 + 1.0) / (n13 - n23) / (n23 - n33 + 2.0) /
                        (n23 - n33 + 1.0) / (n12 - n22 + 2.0) /
                        (n12 - n22 + 1.0));
    }
    double e14_23_22()
    {
      return -std::sqrt((n14 - n23 + 1.0) * (n24 - n23) * (n23 - n34 + 1.0) *
                        (n23 - n44 + 2.0) * (n13 - n22 + 1.0) *
                        (n22 - n33 + 1.0) * (n12 - n23) * (n12 - n11) /
                        (n13 - n23 + 1.0) / (n13 - n23) / (n23 - n33 + 2.0) /
                        (n23 - n33 + 1.0) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e14_33_12()
    {
      return -std::sqrt((n14 - n33 + 2.0) * (n24 - n33 + 1.0) * (n34 - n33) *
                        (n33 - n44 + 1.0) * (n13 - n12) * (n12 - n23 + 1.0) *
                        (n22 - n33) * (n11 - n22 + 1.0) / (n13 - n33 + 2.0) /
                        (n13 - n33 + 1.0) / (n23 - n33 + 1.0) / (n23 - n33) /
                        (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
    double e14_33_22()
    {
      return std::sqrt((n14 - n33 + 2.0) * (n24 - n33 + 1.0) * (n34 - n33) *
                       (n33 - n44 + 1.0) * (n13 - n22 + 1.0) * (n23 - n22) *
                       (n12 - n33 + 1.0) * (n12 - n11) / (n13 - n33 + 2.0) /
                       (n13 - n33 + 1.0) / (n23 - n33 + 1.0) / (n23 - n33) /
                       (n12 - n22 + 1.0) / (n12 - n22));
    }
    //
    double e41_13_12()
    {
      return std::sqrt((n14 - n13 + 1.0) * (n13 - n24) * (n13 - n34 + 1.0) *
                       (n13 - n44 + 2.0) * (n12 - n23) * (n12 - n33 + 1.0) *
                       (n13 - n22 + 1.0) * (n11 - n22) / (n13 - n23 + 1.0) /
                       (n13 - n23) / (n13 - n33 + 2.0) / (n13 - n33 + 1.0) /
                       (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e41_13_22()
    {
      return -std::sqrt((n14 - n13 + 1.0) * (n13 - n24) * (n13 - n34 + 1.0) *
                        (n13 - n44 + 2.0) * (n23 - n22 + 1.0) * (n22 - n33) *
                        (n13 - n12) * (n12 - n11 + 1.0) / (n13 - n23 + 1.0) /
                        (n13 - n23) / (n13 - n33 + 2.0) / (n13 - n33 + 1.0) /
                        (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
    double e41_23_12()
    {
      return -std::sqrt(
          (n14 - n23 + 2.0) * (n24 - n23 + 1.0) * (n23 - n34) *
          (n23 - n44 + 1.0) * (n13 - n12 + 1.0) * (n12 - n33 + 1.0) *
          (n23 - n22) * (n11 - n22) / (n13 - n23 + 2.0) / (n13 - n23 + 1.0) /
          (n23 - n33 + 1.0) / (n23 - n33) / (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e41_23_22()
    {
      return -std::sqrt((n14 - n23 + 2.0) * (n24 - n23 + 1.0) * (n23 - n34) *
                        (n23 - n44 + 1.0) * (n13 - n22 + 2.0) * (n22 - n33) *
                        (n12 - n23 + 1.0) * (n12 - n11 + 1.0) /
                        (n13 - n23 + 2.0) / (n13 - n23 + 1.0) /
                        (n23 - n33 + 1.0) / (n23 - n33) / (n12 - n22 + 2.0) /
                        (n12 - n22 + 1.0));
    }
    double e41_33_12()
    {
      return -std::sqrt((n14 - n33 + 3.0) * (n24 - n33 + 2.0) *
                        (n34 - n33 + 1.0) * (n33 - n44) * (n13 - n12 + 1.0) *
                        (n12 - n23) * (n22 - n33 + 1.0) * (n11 - n22) /
                        (n13 - n33 + 3.0) / (n13 - n33 + 2.0) /
                        (n23 - n33 + 2.0) / (n23 - n33 + 1.0) /
                        (n12 - n22 + 1.0) / (n12 - n22));
    }
    double e41_33_22()
    {
      return std::sqrt(
          (n14 - n33 + 3.0) * (n24 - n33 + 2.0) * (n34 - n33 + 1.0) *
          (n33 - n44) * (n13 - n22 + 2.0) * (n23 - n22 + 1.0) *
          (n12 - n33 + 2.0) * (n12 - n11 + 1.0) / (n13 - n33 + 3.0) /
          (n13 - n33 + 2.0) / (n23 - n33 + 2.0) / (n23 - n33 + 1.0) /
          (n12 - n22 + 2.0) / (n12 - n22 + 1.0));
    }
  };

