  /*------------------------------------------------------
  A structure for U(4) irrep [n14,n24,n34,n44]
  */
  struct irrep
  {
    int n14, n24, n34, n44;

    // Default constructor
    irrep() : n14(0), n24(0), n34(0), n44(0) { }

    // initialization
    irrep(int n1, int n2, int n3, int n4)
    {
      n14 = n1;
      n24 = n2;
      n34 = n3;
      n44 = n4;
    }

    // construction from Draayer's (P1,P2,P3)
    irrep(int P1, int P2, int P3)
    {
      n14 = P1 + P2 + P3;
      n24 = P2 + P3;
      n34 = P3;
      n44 = 0;
    }

    // get back P1, P2, P3
    int P1() { return n14 - n24; }
    int P2() { return n24 - n34; }
    int P3() { return n34 - n44; }

    // assignment operator
    irrep& operator=(const irrep& u4)
    {
      n14 = u4.n14;
      n24 = u4.n24;
      n34 = u4.n34;
      n44 = u4.n44;
      return *this;
    }

    // dimension
    int dim()
    {
      return (1 + n14 - n24) * (2 + n14 - n34) * (3 + n14 - n44) *
             (1 + n24 - n34) * (2 + n24 - n44) * (1 + n34 - n44) / 12;
    }

    // check order of quantum numbers
    bool check()
    {
      if (n14 >= n24 && n24 >= n34 && n34 >= n44)
        return true;
      else
        return false;
    }

    // normalize the irrep
    void normalize()
    {
      n14 -= n44;
      n24 -= n44;
      n34 -= n44;
      n44 = 0;
    }

    // sum of the quantum numbers and also the total number of nucleons
    int n() { return n14 + n24 + n34 + n44; }

    /*
    //O(6) quamtum numbers are calculated at twice their values, which are SU(4)
    quantum numbers used by Wigner int p1p1(){ return (n14 + n24 - n34 - n44);
    }
    int p2p2(){
            return (n14 - n24 + n34 - n44);
    }
    int p3p3(){
            return (n14 - n24 - n34 + n44);
    }

    //Lower limit for S,T
    double gamma_minx2(){
            if ( (n14 + n24 - n34 - n44)%2==0 ){
                    return 0;
            }
            else {
                    return 1;
            }
    }
    */
  };

